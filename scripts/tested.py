#!/usr/bin/env python3
"""Build the public catalog from a complete standard matrix, not supplemental tests.

scripts/tested.py LOG[,LOG...] ORCA_VER BAMBU_VER DATE PRUSA_VER
For the 2026-11-24 baseline, incorporate the dated November 25 evidence.
For a new run, every printer and required output must have its own complete logs.
"""
import json
from pathlib import Path
import re
import sys

PROFILES = Path("client/public/profiles")
SL = {"Bambu": "Bambu Studio", "OrcaS": "OrcaSlicer", "Prusa": "PrusaSlicer"}
STANDARD = {"x1c", "ad5x", "prusa"}
ALIASES = {"paint": "x1c", "psynth": "prusa"}
BASELINE = {"OrcaSlicer": "2.5.2", "Bambu Studio": "02.09.02.62", "PrusaSlicer": "2.9.4"}
MATRIX_NOTE = "The November 24 OrcaSlicer and Bambu Studio matrix allowed mixed filament temperatures. Its passes do not verify stock temperature checks."
RETEST_NOTES = {
    "voron-0-1": ("OrcaSlicer", [0, -52, -52], "Two saved layouts exceeded the bed. Both sliced at full size after rearranging the objects; the original failures still count."),
    "prusa-core-one-mmu3": ("PrusaSlicer", [0] * 8 + [139, 139], "PrusaSlicer stopped during two exports. The project sliced at full size on two plates with both tested nozzles; the original failures still count."),
    "wondermaker-zr": ("OrcaSlicer", [0, 0, -62], "OrcaSlicer rejected the mixed PLA/PETG project. A separate four-color PLA project sliced with the stock temperature check enabled."),
}
SAMPLES = ["4-color painted Bambu Studio project (X1 Carbon, PLA and PETG)",
           "4-color OrcaSlicer project (Flashforge AD5X, PLA)",
           "2-object PrusaSlicer project with a color change (MK4S MMU3, PLA; generated by scripts/make_prusa_fixture.py)",
           "PrusaSlicer output also: two multi-color painted MakerWorld projects (P1S, PLA)"]


def record(results, pid, slicer, tag, rc):
    cases = results.setdefault((pid, slicer), {})
    if cases.setdefault(tag, rc) != rc:
        raise ValueError(f"Conflicting results: {pid}, {slicer}, {tag}. Keep retests separate.")


def read_matrix(logs):
    results = {}
    for path in logs.split(","):
        with open(path) as log:
            for line in log:
                m = re.match(r"(\w+)__(\S+)\s+(\w+)\s+rc=(-?\d+)\b", line)
                if not m:
                    continue
                tag, pid, sl, rc = m.groups()
                # The old adapter relabeled native failures -52. Preserve its recorded
                # process result, not the converter's independent bed-size warning.
                native = re.search(r"; PrusaSlicer rc=(-?\d+)\b", line)
                if sl == "Prusa" and rc == "-52" and native:
                    rc = native[1]
                record(results, pid, SL[sl], ALIASES.get(tag, tag), int(rc))
    return results


def include_wondermaker(results, index):
    """These printers were added after the baseline. Only the three standard cases count."""
    evidence = json.loads((PROFILES.parent / "samples/wondermaker-results.json").read_text())
    if evidence["testedOn"] != "2026-11-25" or evidence["destination"] != "OrcaSlicer 2.5.2":
        raise ValueError("Historical WonderMaker evidence date/version mismatch")
    models = {p["model"]: p["id"] for p in index if p["vendor"] == "WonderMaker"}
    for case in evidence["cases"]:
        if case["project"] in STANDARD:
            record(results, models[case["printer"]], "OrcaSlicer", case["project"], case["returnCode"])
    return set(models.values())


def summarize(pid, slicer, results, variants, historical):
    required = STANDARD | ({"mw147", "mw237"} if slicer == "PrusaSlicer" else set())
    values = []
    for variant in variants:
        cases = results.pop((variant, slicer), {})
        if set(cases) != required:
            raise ValueError(f"Incomplete or nonstandard suite: {variant}, {slicer}: expected {sorted(required)}, got {sorted(cases)}")
        values.extend(cases.values())
    passed = values.count(0)
    row = {"ok": passed == len(values), "passed": passed, "tests": len(values)}
    retest = RETEST_NOTES.get(pid)
    if historical and retest and slicer == retest[0]:
        if sorted(values) != sorted(retest[1]):
            raise ValueError(f"Recorded baseline for {pid} differs from the targeted retest; check inputs")
        row["note"] = retest[2]
    elif -52 in values and slicer != "PrusaSlicer":
        row["note"] = "The sample layout exceeds the bed. Try rearranging objects or using another plate before resizing."
    return row


def build(logs, orca, bambu, date, prusa):
    slicers = {"OrcaSlicer": orca, "Bambu Studio": bambu, "PrusaSlicer": prusa}
    historical = date == "2026-11-24"
    if historical and slicers != BASELINE:
        raise ValueError("Historical baseline slicer versions do not match")
    index = json.loads((PROFILES / "index.json").read_text())
    results = read_matrix(logs)
    added = include_wondermaker(results, index) if historical else set()
    printers = {}
    for p in index:
        pid = p["id"]
        primary = p.get("slicer") or "OrcaSlicer"
        need = ["PrusaSlicer"] if p.get("prusaOnly") else ["PrusaSlicer", primary] if p.get("prusa") else [primary]
        outs = {}
        for sl in need:
            # The native matrix covers all supported nozzles. Other outputs cover the
            # default nozzle, and any additional nozzle must have the complete suite.
            if sl == "PrusaSlicer":
                variants = [pid if n == "0.4" else f"{pid}-n{n.replace('.', '')}" for n in p.get("nozzles", ["0.4"])]
            else:
                variants = [pid] + sorted(v for v, s in results if s == sl and re.fullmatch(re.escape(pid) + r"-n\d\d", v))
            outs[sl] = summarize(pid, sl, results, variants, historical)
        row = {"ok": all(o["ok"] for o in outs.values()), "passed": sum(o["passed"] for o in outs.values()),
               "tests": sum(o["tests"] for o in outs.values()), "slicer": need[0]}
        notes = sorted({o["note"] for o in outs.values() if "note" in o})
        if notes:
            row["note"] = " ".join(notes)
        if len(outs) > 1:
            row["outputs"] = outs
        printers[pid] = {"date": "2026-11-25", **row} if pid in added else row
    if results:
        raise ValueError(f"Unexpected printer/output in the matrix: {next(iter(results))}")
    return {"date": date, "slicers": slicers, **({"baselineNote": MATRIX_NOTE} if historical else {}),
            "samples": SAMPLES, "printers": printers}


if __name__ == "__main__":
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    try:
        doc = build(*sys.argv[1:])
    except (KeyError, ValueError, OSError) as e:
        sys.exit(f"Catalog not written: {e}")
    (PROFILES / "tested.json").write_text(json.dumps(doc, indent=0) + "\n")
    rows = doc["printers"].values()
    print(sum(r["ok"] for r in rows), "of", len(rows), "printers passed all recorded tests")
