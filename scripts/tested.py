#!/usr/bin/env python3
"""Build client/public/profiles/tested.json from slice-matrix logs.
usage: scripts/tested.py LOG[,LOG...] ORCA_VER BAMBU_VER DATE [PRUSA_VER]
  e.g. scripts/tested.py /tmp/all_slice.log,/tmp/pcert.slice.log 2.5.2 02.09.02.62 2026-11-24 2.9.4
A printer is "slicer-tested" when every sample converted for it (all nozzle variants in the logs) sliced (rc=0)
in its destination slicer; rc=-52 (model larger than the bed) is accepted because the converter already warns
and suggests a scale. Lines are grouped by the slicer column of slice-matrix.sh (Bambu / OrcaS / Prusa).
Printers with PrusaSlicer output (index `prusa`/`prusaOnly`) need passing PrusaSlicer slices; `prusa` printers
also offer the OrcaSlicer file, so those slices must pass too. Per-output results go in `outputs`."""
import json, re, sys
logs, orca, bambu, date = sys.argv[1:5]
prusa = sys.argv[5] if len(sys.argv) > 5 else None
SL = {"Bambu": "Bambu Studio", "OrcaS": "OrcaSlicer", "Prusa": "PrusaSlicer"}
res = {}  # variant id -> slicer -> {tag: rc}
for log in logs.split(","):
    for line in open(log):
        m = re.match(r'(\w+)__(\S+)\s+(\w+)\s+rc=(-?\d+)', line)
        if m:
            t, pid, sl, rc = m.groups()
            res.setdefault(pid, {}).setdefault(SL.get(sl, sl), {})[t + "@" + pid] = int(rc)
idx = json.load(open('client/public/profiles/index.json'))

def summary(rs):
    vals = list(rs.values())
    s = {'ok': any(v == 0 for v in vals) and all(v in (0, -52) for v in vals), 'passed': sum(v == 0 for v in vals), 'tests': len(vals)}
    if -52 in vals: s['note'] = 'large models must be scaled to fit this bed'
    return s

out = {}
for p in idx:
    pat = re.compile(re.escape(p['id']) + r'(-n\d\d)?$')
    by = {}
    for pid, d in res.items():
        if pat.match(pid):
            for sl, rs in d.items(): by.setdefault(sl, {}).update(rs)
    if p.get('prusaOnly'): need = ['PrusaSlicer']
    elif p.get('prusa'): need = ['PrusaSlicer', p.get('slicer') or 'OrcaSlicer']
    else: need = [p.get('slicer') or 'OrcaSlicer']
    outs = {sl: summary(by.get(sl, {})) for sl in need}
    rec = {'ok': all(o['ok'] for o in outs.values()), 'passed': sum(o['passed'] for o in outs.values()), 'tests': sum(o['tests'] for o in outs.values()),
           'slicer': need[0]}
    notes = {o['note'] for o in outs.values() if 'note' in o}
    if notes: rec['note'] = '; '.join(sorted(notes))
    if len(need) > 1: rec['outputs'] = outs
    out[p['id']] = rec
slicers = {'OrcaSlicer': orca, 'Bambu Studio': bambu}
if prusa: slicers['PrusaSlicer'] = prusa
samples = ['4-colour painted Bambu Studio project (X1 Carbon, PLA)', '4-colour OrcaSlicer project (Flashforge AD5X, PLA)',
           '2-object PrusaSlicer project with a colour change (MK4S MMU3, PLA; generated by scripts/make_prusa_fixture.py)']
tags = {t.split('@')[0] for d in res.values() for rs in d.values() for t in rs}
if tags & {'mw147', 'mw237'}:
    samples.append('PrusaSlicer output also: two multi-colour painted MakerWorld projects (P1S, PLA)')
json.dump({'date': date, 'slicers': slicers, 'samples': samples, 'printers': out}, open('client/public/profiles/tested.json', 'w'), indent=0)
print(sum(v['ok'] for v in out.values()), 'of', len(out), 'printers tested OK')
for k, v in out.items():
    if not v['ok']: print('  not OK:', k, v)
