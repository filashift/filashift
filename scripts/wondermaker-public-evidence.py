"""Summarize local matrix.ts / slice-matrix.sh outputs without distributing anyone's 3MF."""
from pathlib import Path
import hashlib
import json
import re
import sys

out, bookmark, trim = map(Path, sys.argv[1:4])
models = {"zr": "ZR", "zr-ultra": "ZR Ultra", "zr-ultra-s": "ZR Ultra S"}
fixtures = {"bookmark": 2, "trim": 4, "mw147": 4, "ad5x": 4, "prusa": 2, "x1c": 4}
doc = {
    "testedOn": "2026-11-25", "destination": "OrcaSlicer 2.5.2", "nozzleMm": 0.4,
    "physicallyPrinted": False,
    "manufacturerSlicer": {"name": "Wonderprint-Orca 2.3.2 (Windows CLI under Wine)",
        "control": "Original Bookmark.3mf produced G-code with two filaments.",
        "convertedBookmark": "ZR and ZR Ultra S rejected the project version before slicing. Do not use this workflow with Wonderprint-Orca."},
    "publicFiles": [
        {"tag": "bookmark", "name": "Bookmark.3mf", "page": "https://wondermaker3d.gitbook.io/wondermaker3d/printer-series/zr/documentation-package/model-file-download", "sha256": hashlib.sha256(bookmark.read_bytes()).hexdigest()},
        {"tag": "trim", "name": "Trim_Test_80x80.3mf", "page": "https://github.com/ducati1198/WM_Ultra_Vanilla_Klipper/blob/e98e6534c6ed9f4d686c30215d28dc9c78aeba94/first-layer-stl/Trim_Test_80x80.3mf", "sha256": hashlib.sha256(trim.read_bytes()).hexdigest()}
    ], "cases": [],
}
for tag, expected in fixtures.items():
    for suffix, name in models.items():
        model = "WonderMaker " + name
        folder = out / f"out_{tag}__wondermaker-{suffix}"
        r = json.loads((folder / "result.json").read_text())
        row = {"project": tag, "printer": model, "returnCode": r["return_code"]}
        if r["return_code"]:
            assert (tag, suffix, r["return_code"]) == ("x1c", "zr", -62)
            row["error"] = r["error_string"]
        else:
            g = (folder / "plate_1.gcode").read_text()
            assert "; generated by OrcaSlicer 2.5.2 " in g and f"; printer_model = {model}\n" in g
            tools = sorted(set(map(int, re.findall(r"^T(\d+)\b", g, re.M))))
            amount = list(map(float, re.search(r"^; filament used \[g\] = (.+)$", g, re.M)[1].split(",")))
            assert tools == list(range(expected)) and sum(v > 0 for v in amount) == expected, (tag, model, tools, amount)
            colors = re.search(r"^; filament_colour = (.+)$", g, re.M)[1].split(";")
            if tag == "bookmark":
                assert [c.upper() for c in colors] == ["#FFFFFF", "#FF0000"]
            row.update(filamentChannels=tools, filamentGrams=amount, colors=colors)
        doc["cases"].append(row)
print(json.dumps(doc, indent=2))
