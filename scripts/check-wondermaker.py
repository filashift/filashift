"""Verify the converted ZR Ultra projects' actual stock OrcaSlicer G-code.
Run after matrix.ts and slice-matrix.sh; argument is their shared output directory.
"""
import json
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
for case, count in {"demo": 2, "prusa": 2, "mw147": 4, "x1c": 4, "ad5x": 4}.items():
    folder = root / f"out_{case}__wondermaker-zr-ultra"
    result = json.loads((folder / "result.json").read_text())
    assert result["return_code"] == 0, (case, result)
    text = (folder / "plate_1.gcode").read_text()
    assert "; generated by OrcaSlicer 2.5.2 " in text
    assert "; printer_model = WonderMaker ZR Ultra\n" in text
    used = set(map(int, re.findall(r"^T(\d+)\b", text, re.M)))
    grams = re.search(r"^; filament used \[g\] = (.+)$", text, re.M)
    assert used == set(range(count)), (case, used)
    assert grams and sum(float(g) > 0 for g in grams[1].split(",")) == count, case
    bed = re.search(r"^; first_layer_bed_temperature = (\d+)$", text, re.M)[1]
    assert re.search(rf"^START_PRINT\b[^\n]*\bBED={bed}\b", text, re.M), case
    print(f"{case}: {count} tools with extrusion; first-layer bed command {bed} C")
